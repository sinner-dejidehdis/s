ALREADY_HAVE = ["玻璃缸（已做好）", "铝框架（已做好）", "Delrin 盖板", "16 mm 玻璃膨胀管", "现有甘油和磁流体"]

FILLS = {"必需": "FCE4D6", "建议": "FFF2CC", "可选": "E2EFDA"}


def main():
    wb = Workbook()
    ws = wb.active
    ws.title = "材料清单"
    headers = ["已买", "阶段", "类别", "物品", "规格", "数量", "必需性", "京东链接", "备注"]
    ws.append(headers)
    for c in ws[1]:
        c.font = Font(bold=True, color="FFFFFF")
        c.fill = PatternFill("solid", fgColor="1F4E79")
        c.alignment = Alignment(horizontal="center", vertical="center")
    for stage, cat, item, spec, qty, need, kw, note in ITEMS:
        url = "https://search.jd.com/Search?keyword=" + quote(kw) + "&enc=utf-8"
        ws.append(["☐", stage, cat, item, spec, qty, need, "京东搜索", note])
        r = ws.max_row
        link = ws.cell(row=r, column=8)
        link.hyperlink = url
        link.font = Font(color="0563C1", underline="single")
        key = next((k for k in FILLS if need.startswith(k)), None)
        if key:
            ws.cell(row=r, column=7).fill = PatternFill("solid", fgColor=FILLS[key])
    dv = DataValidation(type="list", formula1='"☐,☑"', allow_blank=True)
    ws.add_data_validation(dv)
    dv.add(f"A2:A{ws.max_row}")
    for col, w in zip("ABCDEFGHI", [6, 8, 12, 24, 36, 18, 18, 11, 26]):
        ws.column_dimensions[col].width = w
    for row in ws.iter_rows(min_row=2):
        for c in row:
            c.alignment = Alignment(vertical="center", wrap_text=True)
    ws.freeze_panes = "A2"

    have = wb.create_sheet("已有不用买")
    have.append(["物品"])
    have["A1"].font = Font(bold=True)
    for x in ALREADY_HAVE:
        have.append([x])
    have.column_dimensions["A"].width = 30

    out = Path(__file__).with_name("materials_list.xlsx")
    wb.save(out)
    print(out, len(ITEMS), "items")


if __name__ == "__main__":
    main()
